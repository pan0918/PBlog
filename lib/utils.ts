import { formatSiteDate } from './datetime';

/**
 * Format a date string to "YYYY.MM.DD" in the site time zone.
 * Returns "刚刚更新" for missing or epoch dates.
 */
export function formatUpdateTime(dateString: string): string {
  if (!dateString || dateString === '1970-01-01') return '刚刚更新';
  return formatSiteDate(dateString) || dateString;
}

/**
 * Format seconds to "M:SS" or "MM:SS" display string.
 */
export function formatTime(time: number): string {
  if (!time || isNaN(time)) return '00:00';
  const m = Math.floor(time / 60).toString().padStart(2, '0');
  const s = Math.floor(time % 60).toString().padStart(2, '0');
  return `${m}:${s}`;
}

/**
 * Normalizes absolute asset URLs so non-ASCII path characters never leak into
 * HTTP resource headers generated by React or Next.js.
 */
export function toBrowserSafeUrl(value: string): string {
  try {
    return new URL(value).href;
  } catch {
    return value;
  }
}
